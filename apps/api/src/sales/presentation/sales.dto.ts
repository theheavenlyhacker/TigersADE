import { ApiProperty } from '@nestjs/swagger';
import { Type } from 'class-transformer';
import { ArrayMaxSize, ArrayMinSize, IsArray, IsIn, IsInt, IsNotEmpty, IsString, IsUUID, Max, MaxLength, Min, ValidateNested } from 'class-validator';
import { IsBusinessDate, trim } from '../../shared/validation';

export const PAYMENT_METHODS = ['cash', 'gcash', 'maya', 'card'] as const;

export class SaleLineDto {
  @ApiProperty() @IsUUID() productId!: string;
  @ApiProperty({ minimum: 1 }) @IsInt() @Min(1) @Max(2147483647) qty!: number;
}

export class RecordSaleDto {
  @ApiProperty({ description: 'Generated by the client; retrying with the same id never double-records' }) @IsUUID() id!: string;
  @ApiProperty({ enum: PAYMENT_METHODS }) @IsIn(PAYMENT_METHODS) paymentMethod!: typeof PAYMENT_METHODS[number];
  @ApiProperty({ type: [SaleLineDto] }) @IsArray() @ArrayMinSize(1) @ArrayMaxSize(100) @ValidateNested({ each: true }) @Type(() => SaleLineDto) lines!: SaleLineDto[];
}

export class VoidSaleDto {
  @ApiProperty() @trim @IsString() @IsNotEmpty() @MaxLength(1000) reason!: string;
}

export class SalesRangeDto {
  @ApiProperty() @IsBusinessDate() from!: string;
  @ApiProperty() @IsBusinessDate() to!: string;
}
